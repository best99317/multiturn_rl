"""
Trajectory-based PPO training script for multi-turn conversation models (Modular Version).
Implements true on-policy PPO where entire conversations are treated as trajectories,
with rewards computed at each turn: ([U1], [A1]), ([U1,A1,U2], [A2]), etc.

This version uses modular reward calculators for better maintainability and extensibility.
Includes improved model loading with vLLM support for faster inference.

Architecture:
- Assistant responses: Generated by PPO model being trained (optionally accelerated with vLLM)
- User responses: Generated by UserSimulator via Bedrock (runs in parallel)
- Trajectory generation: Multiple conversations processed simultaneously

Example usage:
CUDA_VISIBLE_DEVICES=4,5,6,7 torchrun --master_port=56600 --nnodes=1 --nproc_per_node=4 -m scripts.train.trajectory_ppo_modular \
    --dataset_repo path/to/initial_prompts.csv \
    --model_name outputs/sft/my_model \
    --base_model_name meta-llama/Llama-3.1-8B-Instruct \
    --output_dir outputs/trajectory_ppo/my_model \
    --reward_type entropy \
    --max_turns 5 \
    --batch_size 4 \
    --mini_batch_size 2 \
    --learning_rate 1e-6 \
    --use_vllm \
    --user_meta_prompt prompts/user_prompt.txt
"""

